"""Builds SFZ instruments automatically from folders of samples whose filenames contain note names.

e.g. "LLVln_ArcoVib_A4_f.wav", "VlnEns_Pizz_D3_v2_rr1.wav", "UR1_C1_f_RR1.wav"
Tokens: a note (A4, C#3, Bb2), a dynamic (pp..fff or v1..v9) and a round robin (rr1 / RR2 / trailing _1).
"""
from __future__ import annotations

import re
from collections import defaultdict
from pathlib import Path

NOTE_RE = re.compile(r"^([A-Ga-g])([#b]?)(-?\d)$")
DYN_ORDER = ["ppp", "pp", "p", "mp", "mf", "f", "ff", "fff"]
OFFS = {"c": 0, "d": 2, "e": 4, "f": 5, "g": 7, "a": 9, "b": 11}
AUDIO = {".wav", ".flac", ".ogg", ".aif", ".aiff"}


def _note(tok: str) -> int | None:
    m = NOTE_RE.match(tok)
    if not m:
        return None
    l, acc, o = m.groups()
    return OFFS[l.lower()] + (1 if acc == "#" else -1 if acc == "b" else 0) + (int(o) + 1) * 12


def _dyn_rank(tok: str) -> float | None:
    t = tok.lower()
    if t in DYN_ORDER:
        return DYN_ORDER.index(t)
    m = re.fullmatch(r"v(\d+)", t) or re.fullmatch(r"dyn(\d+)", t)
    return float(m.group(1)) if m else None


def parse(name: str):
    toks = re.split(r"[_\s-]+", Path(name).stem)
    note = dyn = None
    for t in toks:
        if note is None and (n := _note(t)) is not None:
            note = n
        elif dyn is None and (d := _dyn_rank(t)) is not None:
            dyn = d
    return note, dyn


def build_sfz(folders: list[Path], root: Path, short: bool = False, release: float | None = None,
              stretch: int = 4) -> str:
    """Return SFZ text mapping all samples in `folders` (paths written relative to `root`)."""
    groups: dict[tuple[int, float], list[Path]] = defaultdict(list)
    for folder in folders:
        for f in sorted(folder.iterdir()):
            if f.suffix.lower() not in AUDIO:
                continue
            note, dyn = parse(f.name)
            if note is None:
                continue
            groups[(note, dyn if dyn is not None else 0.0)].append(f)
    if not groups:
        raise ValueError(f"No note-named samples found in {folders}")
    notes = sorted({n for n, _ in groups})
    layers = sorted({d for _, d in groups})
    rel = release if release is not None else (0.12 if short else 0.45)

    # key ranges: each sampled note covers halfway to its neighbours
    ranges = {}
    for i, n in enumerate(notes):
        lo = notes[0] - stretch if i == 0 else (notes[i - 1] + n) // 2 + 1
        hi = notes[-1] + stretch if i == len(notes) - 1 else (n + notes[i + 1]) // 2
        ranges[n] = (max(0, lo), min(127, hi))

    lines = ["// auto-generated by ai-music-studio automap (sample paths relative to the library root)",
             "<global>", f"ampeg_release={rel}", "ampeg_attack=0.005",
             f"amp_veltrack={60 if len(layers) > 1 else 100}"]
    if short:
        lines.append("loop_mode=one_shot")
    for li, dyn in enumerate(layers):
        lovel = 1 + (127 * li) // len(layers)
        hivel = (127 * (li + 1)) // len(layers)
        lines.append(f"<group> lovel={lovel} hivel={hivel}")
        for n in notes:
            files = groups.get((n, dyn))
            if not files:  # fill a missing layer with the nearest available one
                cands = [d for (nn, d) in groups if nn == n]
                files = groups[(n, min(cands, key=lambda d: abs(d - dyn)))]
            lo, hi = ranges[n]
            k = len(files)
            for ri, f in enumerate(files):
                rr = f" lorand={ri / k:.4f} hirand={(ri + 1) / k:.4f}" if k > 1 else ""
                # sample= last: paths may contain spaces
                lines.append(f"<region> pitch_keycenter={n} lokey={lo} hikey={hi}{rr} "
                             f"sample={f.relative_to(root).as_posix()}")
    return "\n".join(lines) + "\n"
